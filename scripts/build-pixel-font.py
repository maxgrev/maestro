#!/usr/bin/env python3
"""Package the SDK's licensed 5x8 bitmap type and Maestro's pixel controls for LVGL.

No runtime scaling, smoothing, font downloads, or new dependencies.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.cache/muse-gadget-sdk/esp32/main/pixel_font.c'
OUT = ROOT / 'firmware/src'

# Eight square cells per symbol. These retain LVGL's existing symbol codepoints,
# so settings, keyboard and screen-reader text keep their meaning.
ICONS = {
    0xF00B: ['##.#####','##.#####','........','##.#####','##.#####','........','##.#####','##.#####'],
    0xF00C: ['........','.......#','......##','.....##.','#...##..','##.##...','.###....','..#.....'],
    0xF053: ['....##..','...##...','..##....','.##.....','.##.....','..##....','...##...','....##..'],
    0xF054: ['..##....','...##...','....##..','.....##.','.....##.','....##..','...##...','..##....'],
    0xF077: ['...##...','..####..','.##..##.','##....##','........','........','........','........'],
    0xF078: ['........','........','........','........','##....##','.##..##.','..####..','...##...'],
    0xF0E0: ['........','########','##....##','#.#..#.#','#..##..#','#......#','########','........'],
    0xF1EB: ['..####..','.######.','##....##','...##...','..#..#..','........','...##...','...##...'],
    0xF293: ['...#....','...##...','.#.#.#..','..###...','..###...','.#.#.#..','...##...','...#....'],
    0xF026: ['...#....','..##....','####.#.#','####..#.','####.#.#','..##....','...#....','........'],
    0xF028: ['...#..#.','..##...#','####.#.#','####.#.#','####.#.#','..##...#','...#..#.','........'],
    0xF011: ['...##...','...##...','.#.##.#.','##.##.##','##....##','##....##','.##..##.','..####..'],
    0xF015: ['...##...','..####..','.######.','########','.######.','.##..##.','.##..##.','.##..##.'],
    0xF021: ['..####.#','.##..###','##....##','##......','......##','##....##','###..##.','#.####..'],
    0xF044: ['.....##.','....###.','...###..','..###...','.###....','.##.....','.#......','#######.'],
    0xF070: ['#.......','.#.###..','..#...#.','.#.##..#','#..##.#.','.#...#..','..###.#.','.......#'],
    0xF240: ['........','#######.','#.###.##','#.###.##','#.###.##','#.###.##','#######.','........'],
    0xF0E7: ['....##..','...##...','..##....','.#####..','...##...','..##....','.##.....','........'],
    0xF00D: ['##....##','.##..##.','..####..','...##...','...##...','..####..','.##..##.','##....##'],
    0xE000: ['..###...','..###...','..###...','#.###.#.','#.###.#.','.#####..','...#....','..###...'],
}


def main():
    source = SOURCE.read_text()
    license = source[:source.index('#include')]
    columns = [[int(n, 16) for n in re.findall(r'0x[0-9a-f]+', row)]
               for row in re.findall(r'\{([^{}]+)\},', source)]
    assert len(columns) == 95
    glyphs = {i + 32: [[(col >> y) & 1 for col in row] for y in range(8)]
              for i, row in enumerate(columns)}
    for code, rows in ICONS.items():
        assert len(rows) == 8 and all(len(row) == 8 for row in rows)
        glyphs[code] = [[c == '#' for c in row] for row in rows]
    for code, char in {0xa0:' ',0xb7:'.',0x2013:'-',0x2014:'-',0x2018:"'",0x2019:"'",0x201c:'"',0x201d:'"',0x2022:'.'}.items():
        glyphs[code] = glyphs[ord(char)]
    glyphs[0x2026] = [[int(y == 6 and x in (0, 2, 4)) for x in range(5)] for y in range(8)]
    codes = sorted(glyphs)
    text = license + '// Generated by scripts/build-pixel-font.py. Do not edit.\n#include "maestro_font.h"\n'
    for height, scale in [(16,2),(20,2),(24,3)]:
        name = f'maestro_font_{height}'
        data, descriptions = [], ['{0}']
        for code in codes:
            rows = glyphs[code]
            width = len(rows[0]) * scale
            bits = [int(v) for row in rows for _ in range(scale) for v in row for _ in range(scale)]
            start = len(data)
            data += [sum(v << (7 - j) for j,v in enumerate(bits[i:i+8])) for i in range(0,len(bits),8)]
            descriptions.append(f'{{.bitmap_index={start},.adv_w={(width+scale)*16},.box_w={width},.box_h={8*scale},.ofs_y={height-8*scale}}}')
        text += f'static const uint8_t {name}_bitmap[] = {{\n'
        text += '\n'.join(','.join(hex(v) for v in data[i:i+24])+',' for i in range(0,len(data),24)) + '\n};\n'
        text += f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{\n' + ',\n'.join(descriptions) + '\n};\n'
        text += f'static const uint16_t {name}_codes[] = {{' + ','.join(str(c-32) for c in codes) + '};\n'
        text += f'static const lv_font_fmt_txt_cmap_t {name}_map[] = {{{{.range_start=32,.range_length={max(codes)-31},.glyph_id_start=1,.unicode_list={name}_codes,.list_length={len(codes)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};\n'
        text += f'static const lv_font_fmt_txt_dsc_t {name}_dsc = {{.glyph_bitmap={name}_bitmap,.glyph_dsc={name}_glyphs,.cmaps={name}_map,.cmap_num=1,.bpp=1}};\n'
        # Preserve non-Latin user text. UI labels and common punctuation use the
        # bitmap font; unsupported glyphs retain LVGL's shipped fallback.
        fallback = 20 if height == 20 else 16 if height == 16 else 28
        text += f'const lv_font_t {name} = {{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={height},.dsc=&{name}_dsc,.fallback=&lv_font_montserrat_{fallback}}};\n'
    (OUT / 'maestro_font.c').write_text(text)


if __name__ == '__main__':
    main()
