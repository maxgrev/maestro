#!/usr/bin/env python3
"""Convert the bundled Codex companion into RGB565 frames for this private build.

The source art is OpenAI's installed Codex companion, not an MIT-licensed asset.
This converts its format and size; it does not redraw the character.
Requires Pillow 12.3.0 (build time only).
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SHEET = ROOT / "bridge/public/characters/codex.webp"
OUTPUT = ROOT / "firmware/src/avatars/codex.h"
ROWS = [(0, 6), (3, 4), (7, 6), (8, 6), (5, 8), (6, 6)]


def main():
    sheet = Image.open(SHEET).convert("RGBA")
    if sheet.size != (1536, 2288):
        raise SystemExit("Unexpected Codex sprite layout")
    words, offsets = [], [0]
    for row, count in ROWS:
        for col in range(count):
            frame = sheet.crop((col * 192, row * 208, (col + 1) * 192, (row + 1) * 208)).resize((80, 87), Image.Resampling.LANCZOS)
            last, run = None, 0
            for r, g, b, a in frame.get_flattened_data():
                # Composite the supplied alpha onto the display's black canvas.
                r, g, b = r*a//255, g*a//255, b*a//255
                value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                if value == last:
                    run += 1
                else:
                    if run: words.extend([last, run])
                    last, run = value, 1
            words.extend([last, run]); offsets.append(len(words))
    text = "// Generated by scripts/build-codex-sprites.py. See SOURCES.md.\n#pragma once\n#include <stdint.h>\n"
    text += "static const uint32_t codex_offsets[] = {" + ",".join(map(str, offsets)) + "};\n"
    text += "static const uint16_t codex_data[] = {\n"
    text += "\n".join(",".join(hex(v) for v in words[i:i+20])+"," for i in range(0, len(words), 20)) + "\n};\n"
    OUTPUT.write_text(text)
    print(f"Codex: {len(offsets)-1} frames, {len(words)*2:,} bytes")


if __name__ == "__main__":
    main()
