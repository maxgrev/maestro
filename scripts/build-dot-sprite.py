#!/usr/bin/env python3
"""Encode the generated Dot artwork on a 48-cell RGB565 grid for the display."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'bridge/public/characters/dot.png'
OUTPUT = ROOT / 'firmware/src/avatars/dot.h'


def main():
    art = Image.open(SOURCE).convert('RGBA')
    # Transparent RGB565 pixels use zero. Ignore near-transparent edge noise.
    bounds = art.getchannel('A').point(lambda a: 255 if a >= 128 else 0).getbbox()
    art = art.crop(bounds)
    art.thumbnail((48, 48), Image.Resampling.NEAREST)
    cells = Image.new('RGBA', (48, 48))
    cells.paste(art, ((48-art.width)//2, (48-art.height)//2))
    colors = cells.convert('RGB').quantize(colors=8, dither=Image.Dither.NONE).convert('RGB')
    words = []
    for (r,g,b), a in zip(colors.get_flattened_data(), cells.getchannel('A').get_flattened_data()):
        words.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if a >= 128 else 0)
    OUTPUT.write_text('// Generated by scripts/build-dot-sprite.py. See SOURCES.md.\n'
                      '#pragma once\n#include <stdint.h>\nstatic const uint16_t dot_sprite[48 * 48] = {\n' +
                      '\n'.join(','.join(hex(v) for v in words[i:i+24])+',' for i in range(0,len(words),24)) + '\n};\n')


if __name__ == '__main__':
    main()
